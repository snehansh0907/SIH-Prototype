/**
 * Dynamic content helper for veterinary expert greeting with animal species, disease, and severity parameters
 */
export const getExpertInitialGreeting = (
  lang: 'en' | 'hi' | 'mr',
  cropName: string,
  diseaseName: string,
  severity: string
): string => {
  if (lang === 'mr') {
    return `नमस्ते पशुपालक मित्र! (पशु संजीवनी सल्ला केंद्र). मी आपल्या गोठ्यातील ${cropName} अहवाल पाहिला (${diseaseName} - ${severity}). किती जनावरे बाधित आहेत आणि आपण जनावराला वेगळे बांधले आहे का?`;
  }
  if (lang === 'hi') {
    return `नमस्ते पशुपालक भाई! (पशु संजीवनी डेस्क)। मैंने आपके गोठे के ${cropName} निदान (${diseaseName} - ${severity}) की समीक्षा की है। कितने पशु प्रभावित हैं, और क्या आपने संक्रमित पशु को अलग शेड में बांधा है?`;
  }
  return `Namaste livestock owner! (Pashu Sanjeevani Desk). I reviewed your ${cropName} diagnosis (${diseaseName} - ${severity}). How many animals in your herd are showing symptoms, and have you quarantined them in a separate shed?`;
};
