export const getExpertInitialGreeting = (
  language: 'en' | 'hi' | 'mr',
  param2?: string,
  param3?: string,
  param4?: string
): string => {
  if (param4) {
    const cropName = param2 || 'Livestock';
    const diseaseName = param3 || 'Condition';
    const severity = param4 || 'moderate';
    if (language === 'mr') {
      return `नमस्ते पशुपालक मित्र! (पशु संजीवनी सल्ला केंद्र). मी आपल्या गोठ्यातील ${cropName} अहवाल पाहिला (${diseaseName} - ${severity}). किती जनावरे बाधित आहेत आणि आपण जनावराला वेगळे बांधले आहे का?`;
    }
    if (language === 'hi') {
      return `नमस्ते पशुपालक भाई! (पशु संजीवनी डेस्क)। मैंने आपके गोठे के ${cropName} निदान (${diseaseName} - ${severity}) की समीक्षा की है। कितने पशु प्रभावित हैं, और क्या आपने संक्रमित पशु को अलग शेड में बांधा है?`;
    }
    return `Namaste livestock owner! (Pashu Sanjeevani Desk). I reviewed your ${cropName} diagnosis (${diseaseName} - ${severity}). How many animals in your herd are showing symptoms, and have you quarantined them in a separate shed?`;
  }

  const name = param2 ? ` ${param2}` : '';
  const animal = param3 || 'Livestock';

  if (language === 'mr') {
    return `नमस्कार${name}! मी डॉ. अरविंद देशमुख (वरिष्ठ पशुवैद्यकीय अधिकारी, KVK नाशिक). तुमच्या ${animal} बाबत काय लक्षणे दिसत आहेत? आपण औषधोपचार, लसीकरण किंवा आहाराबाबत चर्चा करू शकता.`;
  }
  if (language === 'hi') {
    return `नमस्ते${name}! मैं डॉ. अरविंद देशमुख (वरिष्ठ पशु चिकित्सा अधिकारी, KVK नाशिक). आपके ${animal} में क्या लक्षण दिखाई दे रहे हैं? हम उपचार, टीकाकरण या देखभाल पर चर्चा कर सकते हैं।`;
  }
  return `Namaste${name}! I am Dr. Arvind Deshmukh (Senior Veterinary Officer, KVK Nashik). How is your ${animal} doing today? Feel free to ask about symptoms, treatments, vaccinations, or nutrition.`;
};
